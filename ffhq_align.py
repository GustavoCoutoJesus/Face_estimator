"""
FFHQ-style facial landmark detection and alignment for naturalistic photographs.

The One Million Impressions (OMI) dataset (Peterson et al., 2022, PNAS) uses
synthetic faces generated by StyleGAN2 trained on FFHQ. To accurately estimate
perceived social traits on real, naturalistic photographs, input faces should
be aligned using the exact FFHQ geometric convention (eye line leveled,
inter-ocular / eye-to-mouth scale standardized, reflection-padded borders).
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import List, Optional, Tuple, Union

import cv2
import numpy as np
import scipy.ndimage
from PIL import Image


# MediaPipe 468-landmark indices (image-space left vs right)
# Image-left eye (subject's right eye)
MP_LEFT_EYE_IDXS = [33, 133, 159, 145, 158, 153]
# Image-right eye (subject's left eye)
MP_RIGHT_EYE_IDXS = [362, 263, 386, 374, 385, 380]
# Image-left and image-right mouth corners
MP_MOUTH_LEFT_IDX = 61
MP_MOUTH_RIGHT_IDX = 291


@dataclass
class FaceLandmarks:
    """Key facial landmarks in pixel coordinates (x, y)."""
    eye_left: np.ndarray     # (2,) eye on the left side of the image
    eye_right: np.ndarray    # (2,) eye on the right side of the image
    mouth_left: np.ndarray   # (2,) mouth corner on the left side of the image
    mouth_right: np.ndarray  # (2,) mouth corner on the right side of the image
    bbox_area: float = 0.0


def detect_landmarks_mediapipe(
    img_rgb: np.ndarray,
    max_faces: int = 5,
) -> List[FaceLandmarks]:
    """Detect facial landmarks using MediaPipe FaceMesh, sorted largest-face-first."""
    import mediapipe as mp

    h, w = img_rgb.shape[:2]
    mp_face_mesh = mp.solutions.face_mesh
    detected: List[FaceLandmarks] = []

    with mp_face_mesh.FaceMesh(
        static_image_mode=True,
        max_num_faces=max_faces,
        refine_landmarks=True,
        min_detection_confidence=0.3,
    ) as face_mesh:
        results = face_mesh.process(img_rgb)
        if not results.multi_face_landmarks:
            return []

        for face_lms in results.multi_face_landmarks:
            coords = np.array(
                [[lm.x * w, lm.y * h] for lm in face_lms.landmark],
                dtype=np.float64,
            )
            eye_left = coords[MP_LEFT_EYE_IDXS].mean(axis=0)
            eye_right = coords[MP_RIGHT_EYE_IDXS].mean(axis=0)
            mouth_left = coords[MP_MOUTH_LEFT_IDX]
            mouth_right = coords[MP_MOUTH_RIGHT_IDX]

            min_xy = coords[:468].min(axis=0)
            max_xy = coords[:468].max(axis=0)
            area = float((max_xy[0] - min_xy[0]) * (max_xy[1] - min_xy[1]))

            detected.append(
                FaceLandmarks(
                    eye_left=eye_left,
                    eye_right=eye_right,
                    mouth_left=mouth_left,
                    mouth_right=mouth_right,
                    bbox_area=area,
                )
            )

    detected.sort(key=lambda f: f.bbox_area, reverse=True)
    return detected


def detect_landmarks_opencv_fallback(img_rgb: np.ndarray) -> List[FaceLandmarks]:
    """Fallback OpenCV Haar cascade detector if MediaPipe is unavailable or fails."""
    gray = cv2.cvtColor(img_rgb, cv2.COLOR_RGB2GRAY)
    face_cascade = cv2.CascadeClassifier(
        cv2.data.haarcascades + "haarcascade_frontalface_default.xml"
    )
    faces = face_cascade.detectMultiScale(gray, scaleFactor=1.1, minNeighbors=4)
    if len(faces) == 0:
        return []

    # Sort largest face first
    faces = sorted(faces, key=lambda b: b[2] * b[3], reverse=True)
    results: List[FaceLandmarks] = []
    for (x, y, fw, fh) in faces:
        # Approximate standard anthropometry within frontal face bounding box
        eye_left = np.array([x + 0.32 * fw, y + 0.38 * fh], dtype=np.float64)
        eye_right = np.array([x + 0.68 * fw, y + 0.38 * fh], dtype=np.float64)
        mouth_left = np.array([x + 0.36 * fw, y + 0.74 * fh], dtype=np.float64)
        mouth_right = np.array([x + 0.64 * fw, y + 0.74 * fh], dtype=np.float64)
        results.append(
            FaceLandmarks(
                eye_left=eye_left,
                eye_right=eye_right,
                mouth_left=mouth_left,
                mouth_right=mouth_right,
                bbox_area=float(fw * fh),
            )
        )
    return results


def align_face_ffhq(
    img: Union[str, Path, Image.Image, np.ndarray],
    landmarks: Optional[FaceLandmarks] = None,
    output_size: int = 512,
    enable_padding: bool = True,
) -> Tuple[Image.Image, bool]:
    """
    Align and crop a face image using the official NVIDIA FFHQ alignment geometry.

    Parameters
    ----------
    img : path, PIL.Image, or RGB numpy array
        Input naturalistic photograph.
    landmarks : FaceLandmarks, optional
        Pre-detected landmarks. If None, runs MediaPipe FaceMesh (with OpenCV fallback).
    output_size : int
        Output square resolution in pixels (default 512).
    enable_padding : bool
        Whether to apply reflective blurred border padding when the FFHQ frame
        extends beyond the original photo boundaries (prevents black borders on
        tightly-cropped portraits).

    Returns
    -------
    aligned_pil : PIL.Image.Image
        Aligned RGB face image.
    face_detected : bool
        True if a face was detected and aligned; False if fallback center-crop was used.
    """
    if isinstance(img, (str, Path)):
        pil_img = Image.open(img).convert("RGB")
    elif isinstance(img, np.ndarray):
        pil_img = Image.fromarray(img).convert("RGB")
    else:
        pil_img = img.convert("RGB")

    img_rgb = np.array(pil_img)

    if landmarks is None:
        detected = detect_landmarks_mediapipe(img_rgb)
        if not detected:
            detected = detect_landmarks_opencv_fallback(img_rgb)
        if not detected:
            # Fallback: square center-crop if no face detector triggered
            w, h = pil_img.size
            side = min(w, h)
            left = (w - side) // 2
            top = (h - side) // 2
            cropped = pil_img.crop((left, top, left + side, top + side)).resize(
                (output_size, output_size), Image.Resampling.BICUBIC
            )
            return cropped, False
        landmarks = detected[0]

    eye_left = landmarks.eye_left
    eye_right = landmarks.eye_right
    mouth_left = landmarks.mouth_left
    mouth_right = landmarks.mouth_right

    # Official FFHQ oriented crop rectangle geometry
    eye_avg = (eye_left + eye_right) * 0.5
    eye_to_eye = eye_right - eye_left
    mouth_avg = (mouth_left + mouth_right) * 0.5
    eye_to_mouth = mouth_avg - eye_avg

    x = eye_to_eye - np.flipud(eye_to_mouth) * [-1.0, 1.0]
    x /= np.hypot(*x)
    x *= max(np.hypot(*eye_to_eye) * 2.0, np.hypot(*eye_to_mouth) * 1.8)
    y = np.flipud(x) * [-1.0, 1.0]
    c = eye_avg + eye_to_mouth * 0.1
    quad = np.stack([c - x - y, c - x + y, c + x + y, c + x - y])
    qsize = float(np.hypot(*x) * 2.0)

    # Shrink if source image is much larger than target
    shrink = int(np.floor(qsize / output_size * 0.5))
    if shrink > 1:
        rsize = (
            int(np.rint(float(pil_img.size[0]) / shrink)),
            int(np.rint(float(pil_img.size[1]) / shrink)),
        )
        pil_img = pil_img.resize(rsize, Image.Resampling.LANCZOS)
        quad /= shrink
        qsize /= shrink

    # Crop outer bounding box
    border = max(int(np.rint(qsize * 0.1)), 3)
    crop = (
        int(np.floor(min(quad[:, 0]))),
        int(np.floor(min(quad[:, 1]))),
        int(np.ceil(max(quad[:, 0]))),
        int(np.ceil(max(quad[:, 1]))),
    )
    crop = (
        max(crop[0] - border, 0),
        max(crop[1] - border, 0),
        min(crop[2] + border, pil_img.size[0]),
        min(crop[3] + border, pil_img.size[1]),
    )
    if crop[2] - crop[0] < pil_img.size[0] or crop[3] - crop[1] < pil_img.size[1]:
        pil_img = pil_img.crop(crop)
        quad -= [crop[0], crop[1]]

    # Reflective border padding with smooth transition if crop reaches outside image
    pad = (
        int(np.floor(min(quad[:, 0]))),
        int(np.floor(min(quad[:, 1]))),
        int(np.ceil(max(quad[:, 0]))),
        int(np.ceil(max(quad[:, 1]))),
    )
    pad = (
        max(-pad[0] + border, 0),
        max(-pad[1] + border, 0),
        max(pad[2] - pil_img.size[0] + border, 0),
        max(pad[3] - pil_img.size[1] + border, 0),
    )
    if enable_padding and max(pad) > border - 4:
        pad = np.maximum(pad, int(np.rint(qsize * 0.3)))
        img_arr = np.pad(
            np.float32(pil_img),
            ((pad[1], pad[3]), (pad[0], pad[2]), (0, 0)),
            "reflect",
        )
        h, w, _ = img_arr.shape
        y_grid, x_grid, _ = np.ogrid[:h, :w, :1]
        mask = np.maximum(
            1.0 - np.minimum(
                np.float32(x_grid) / max(pad[0], 1),
                np.float32(w - 1 - x_grid) / max(pad[2], 1),
            ),
            1.0 - np.minimum(
                np.float32(y_grid) / max(pad[1], 1),
                np.float32(h - 1 - y_grid) / max(pad[3], 1),
            ),
        )
        blur = qsize * 0.02
        img_arr += (
            scipy.ndimage.gaussian_filter(img_arr, [blur, blur, 0]) - img_arr
        ) * np.clip(mask * 3.0 + 1.0, 0.0, 1.0)
        img_arr += (np.median(img_arr, axis=(0, 1)) - img_arr) * np.clip(
            mask, 0.0, 1.0
        )
        pil_img = Image.fromarray(np.uint8(np.clip(np.rint(img_arr), 0, 255)), "RGB")
        quad += pad[:2]

    # Transform quad into square output_size x output_size image
    pil_img = pil_img.transform(
        (output_size, output_size),
        Image.Transform.QUAD,
        (quad + 0.5).flatten(),
        Image.Resampling.BILINEAR,
    )
    return pil_img, True
